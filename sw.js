async function scopedClients() {
  const scope = new URL(ROOT);
  return (await self.clients.matchAll({ type: 'window', includeUncontrolled: true })).filter(client => { try { const url = new URL(client.url); return url.origin === scope.origin && url.pathname.startsWith(scope.pathname); } catch { return false; } });
}
function ask(client, data, timeout = 12000) {
  return new Promise(resolve => {
    const channel = new MessageChannel(), timer = setTimeout(() => { channel.port1.close(); resolve({ ok: false, reason: 'unresponsive', clientId: client.id }); }, timeout);
    channel.port1.onmessage = event => { clearTimeout(timer); channel.port1.close(); resolve({ ...event.data, clientId: client.id }); };
    try { client.postMessage(data, [channel.port2]); } catch { clearTimeout(timer); resolve({ ok: false, reason: 'unreachable', clientId: client.id }); }
  });
}
